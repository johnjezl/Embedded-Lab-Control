"""Unit tests for udev rule generation."""

import pytest

from labctl.core.models import SerialDevice
from labctl.serial.udev import UDEV_HEADER, generate_udev_rules


class TestGenerateUdevRules:
    """Tests for generate_udev_rules function."""

    def test_empty_device_list(self):
        """Test generating rules with no devices."""
        result = generate_udev_rules([])
        assert result.startswith(UDEV_HEADER)
        # Only the header, no device-specific lines
        lines = result.strip().splitlines()
        header_lines = UDEV_HEADER.strip().splitlines()
        assert len(lines) == len(header_lines)

    def test_single_device(self):
        """Test generating rules for a single device."""
        device = SerialDevice(
            id=1,
            name="sbc1-console",
            usb_path="1-10.1.3",
            vendor="FTDI",
            model="FT232R",
        )
        result = generate_udev_rules([device])

        assert UDEV_HEADER in result
        assert "# sbc1-console (FTDI, FT232R)" in result
        assert (
            'SUBSYSTEM=="tty", KERNELS=="1-10.1.3", '
            'SYMLINK+="lab/sbc1-console", GROUP="dialout", MODE="0660"'
        ) in result

    def test_multiple_devices_sorted_by_name(self):
        """Test that devices are sorted by name in output."""
        devices = [
            SerialDevice(id=1, name="z-device", usb_path="1-1.1"),
            SerialDevice(id=2, name="a-device", usb_path="1-1.2"),
            SerialDevice(id=3, name="m-device", usb_path="1-1.3"),
        ]
        result = generate_udev_rules(devices)

        lines = result.splitlines()
        comment_lines = [
            line
            for line in lines
            if line.startswith("# ") and line not in UDEV_HEADER.splitlines()
        ]
        assert len(comment_lines) == 3
        assert comment_lines[0] == "# a-device"
        assert comment_lines[1] == "# m-device"
        assert comment_lines[2] == "# z-device"

    def test_device_with_vendor_only(self):
        """Test comment format with only vendor set."""
        device = SerialDevice(
            id=1,
            name="test-dev",
            usb_path="2-1.1",
            vendor="Prolific",
        )
        result = generate_udev_rules([device])

        assert "# test-dev (Prolific)" in result

    def test_device_with_model_only(self):
        """Test comment format with only model set."""
        device = SerialDevice(
            id=1,
            name="test-dev",
            usb_path="2-1.1",
            model="PL2303",
        )
        result = generate_udev_rules([device])

        assert "# test-dev (PL2303)" in result

    def test_device_with_no_vendor_no_model(self):
        """Test comment format with no vendor or model."""
        device = SerialDevice(
            id=1,
            name="bare-dev",
            usb_path="3-1.1",
        )
        result = generate_udev_rules([device])

        # Comment should just be the name, no parentheses
        assert "# bare-dev\n" in result
        assert "()" not in result

    def test_rule_format_structure(self):
        """Test the overall structure of a generated rule block."""
        device = SerialDevice(
            id=1,
            name="my-adapter",
            usb_path="1-5.2.1",
            vendor="FTDI",
            model="FT4232H",
        )
        result = generate_udev_rules([device])
        lines = result.splitlines()

        # Find the device-specific lines (after header)
        device_lines = []
        found_header_end = False
        for line in lines:
            if found_header_end:
                device_lines.append(line)
            elif line == "" and device_lines == []:
                # Empty line after header could be separator; check next
                pass
            if line.startswith("# my-adapter"):
                found_header_end = True
                device_lines.append(line)

        # Should have: comment line, rule line, blank line
        assert len(device_lines) >= 2
        assert device_lines[0] == "# my-adapter (FTDI, FT4232H)"
        assert device_lines[1].startswith('SUBSYSTEM=="tty"')
        assert 'KERNELS=="1-5.2.1"' in device_lines[1]
        assert 'SYMLINK+="lab/my-adapter"' in device_lines[1]
        assert 'GROUP="dialout", MODE="0660"' in device_lines[1]

    def test_header_content(self):
        """Test that the header contains expected content."""
        result = generate_udev_rules([])
        assert "Lab Controller Serial Device Rules" in result
        assert "Auto-generated by labctl" in result
        assert "do not edit manually" in result
        assert "labctl serial udev --install" in result


class TestDeviceGroupNote:
    @pytest.fixture
    def dialout(self, monkeypatch):
        """A dialout group (gid 20) whose only listed member is 'alice';
        pwd knows alice and bob (primary gid 1000) and carol (primary 20)."""
        import grp
        import pwd

        monkeypatch.setattr(
            grp,
            "getgrnam",
            lambda name: type("G", (), {"gr_gid": 20, "gr_mem": ["alice"]})(),
        )
        gids = {"alice": 1000, "bob": 1000, "carol": 20}
        entry = lambda name: type(  # noqa: E731
            "P", (), {"pw_name": name, "pw_gid": gids[name]}
        )()
        monkeypatch.setattr(pwd, "getpwnam", entry)
        monkeypatch.setattr(
            pwd, "getpwuid", lambda uid: entry({1001: "alice", 1002: "bob"}[uid])
        )
        monkeypatch.setattr("os.getegid", lambda: 1000)

    def test_no_such_group(self, monkeypatch):
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 1000)
        assert device_group_note("no-such-group-labctl") is None

    def test_process_in_group(self, monkeypatch, dialout):
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 1002)
        monkeypatch.setattr("os.getgroups", lambda: [1000, 20])
        assert device_group_note() is None

    def test_not_a_member_is_told_to_join(self, monkeypatch, dialout):
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 1002)
        monkeypatch.setattr("os.getgroups", lambda: [1000])
        note = device_group_note()
        assert "sudo usermod -aG dialout bob" in note
        assert "console --direct" in note

    def test_member_without_new_login_is_told_to_log_in(self, monkeypatch, dialout):
        """Added with usermod, but this session predates it."""
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 1001)
        monkeypatch.setattr("os.getgroups", lambda: [1000])
        note = device_group_note()
        assert "log in again: alice was added to dialout" in note
        assert "usermod" not in note

    def test_plain_root_needs_nothing(self, monkeypatch, dialout):
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 0)
        monkeypatch.delenv("SUDO_USER", raising=False)
        assert device_group_note() is None

    @pytest.mark.parametrize(
        "user, joins", [("alice", False), ("carol", False), ("bob", True)]
    )
    def test_under_sudo_checks_the_invoking_user(
        self, monkeypatch, dialout, user, joins
    ):
        """Installing the rules usually needs sudo: the note is about the
        user who ran it, not root."""
        from labctl.serial.udev import device_group_note

        monkeypatch.setattr("os.geteuid", lambda: 0)
        monkeypatch.setenv("SUDO_USER", user)
        note = device_group_note()
        if joins:
            assert f"sudo usermod -aG dialout {user}" in note
        else:
            assert note is None


class TestSerialUdevInstallNote:
    """`labctl serial udev --install` says when the user can't open the
    devices it just made root:dialout 0660."""

    @pytest.fixture
    def run(self, tmp_path, monkeypatch):
        from click.testing import CliRunner

        from labctl.cli import main
        from labctl.core.manager import get_manager

        db_path = tmp_path / "labctl.db"
        config_path = tmp_path / "config.yaml"
        config_path.write_text(f"database_path: {db_path}\n")
        get_manager(db_path).create_serial_device("adapter", "1-4.2")
        installed = []
        monkeypatch.setattr(
            "labctl.serial.udev.install_udev_rules",
            lambda rules: installed.append(rules),
        )

        def run(missing):
            note = "the devices are root:dialout 0660 ... join" if missing else None
            monkeypatch.setattr("labctl.serial.udev.device_group_note", lambda: note)
            result = CliRunner().invoke(
                main, ["-c", str(config_path), "serial", "udev", "--install"]
            )
            assert result.exit_code == 0, result.output
            assert installed
            return result

        return run

    def test_note_when_not_in_dialout(self, run):
        result = run(missing=True)
        assert "Note: the devices are root:dialout 0660 ... join." in result.stderr

    def test_no_note_when_in_dialout(self, run):
        assert "dialout" not in run(missing=False).output


class TestRuleLinks:
    """Which /dev/lab links a rules file creates, and which an install
    would change (the claim check of `serial udev --install`, #41)."""

    def test_round_trips_generated_rules(self):
        from labctl.serial.udev import rule_links

        rules = generate_udev_rules(
            [
                SerialDevice(id=1, name="port-a", usb_path="1-1.1", vendor="FTDI"),
                SerialDevice(id=2, name="port-b", usb_path="1-1.2"),
            ]
        )
        assert rule_links(rules) == {"port-a": "1-1.1", "port-b": "1-1.2"}

    def test_ignores_comments_and_other_rules(self):
        from labctl.serial.udev import rule_links

        text = (
            '# SUBSYSTEM=="tty", KERNELS=="1-1.1", SYMLINK+="lab/old"\n'
            'SUBSYSTEM=="tty", KERNELS=="1-1.2", SYMLINK+="other/x"\n'
            'SUBSYSTEM=="tty", KERNELS=="1-1.3", SYMLINK+="lab/c", MODE="0660"\n'
        )
        assert rule_links(text) == {"c": "1-1.3"}

    def test_changed_links(self):
        from labctl.serial.udev import changed_links

        old = {"kept": "1-1", "moved": "1-2", "gone": "1-3"}
        new = {"kept": "1-1", "moved": "1-9", "added": "1-4"}
        assert changed_links(old, new) == {"moved", "gone"}

    def test_installed_rule_links(self, tmp_path):
        from labctl.serial.udev import installed_rule_links

        path = tmp_path / "99-lab-serial.rules"
        assert installed_rule_links(path) == {}  # none installed yet
        path.write_text(
            generate_udev_rules([SerialDevice(id=1, name="a", usb_path="1-1.1")])
        )
        assert installed_rule_links(path) == {"a": "1-1.1"}

    def test_unreadable_rules_file_is_none(self, tmp_path):
        from labctl.serial.udev import installed_rule_links

        path = tmp_path / "99-lab-serial.rules"
        path.mkdir()
        assert installed_rule_links(path) is None

    def test_default_path_read_at_call_time(self, tmp_path, monkeypatch):
        from labctl.serial import udev

        path = tmp_path / "rules"
        path.write_text('SUBSYSTEM=="tty", KERNELS=="1-2", SYMLINK+="lab/x"\n')
        monkeypatch.setattr(udev, "UDEV_RULES_PATH", path)
        assert udev.installed_rule_links() == {"x": "1-2"}
